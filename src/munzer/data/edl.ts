/**
 * The edit. One entry per shot, in order; a shot runs until the next one
 * starts. `at` is seconds of the narration MP3 (or `{ ins, t }` inside an
 * insert, see engine/timeline.ts). Every cut was placed against the word
 * timings of the voice track; the comment on each line is the narration
 * the shot carries.
 *
 * Rule of the edit: no piece of archive is used twice. `src` is where a
 * clip shot starts in its source; tools/munzer-ledger.mjs checks that no
 * two shots (or stills) draw on overlapping source time.
 */

type ClipOpts = Omit<ClipShot, "id" | "at" | "kind" | "clip" | "src">;

const c = (id: string, at: Shot["at"], clip: ClipId, src: number, o: ClipOpts = {}): Shot => ({
  id,
  at,
  kind: "clip",
  clip,
  src,
  ...o,
});

const p = (id: string, at: Shot["at"], photo: PhotoId, o: Partial<Extract<Shot, { kind: "photo" }>> = {}): Shot => ({
  id,
  at,
  kind: "photo",
  photo,
  ...o,
});

/** A frame pulled from the archive video, shown as a still. */
const s = (
  id: string,
  at: Shot["at"],
  file: string,
  w: number,
  h: number,
  o: Partial<Extract<Shot, { kind: "photo" }>> = {},
): Shot => ({ id, at, kind: "photo", still: { file, w, h }, ...o });

const a = (
  id: string,
  at: Shot["at"],
  anim: string,
  props: Record<string, unknown> = {},
  o: Partial<Extract<Shot, { kind: "anim" }>> = {},
): Shot => ({ id, at, kind: "anim", anim, props, ...o });

const F = (x: number, y: number, z = 1) => ({ x, y, z });

