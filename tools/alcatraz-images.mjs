/**
 * Normalises the stills listed in `tools/alcatraz-images.json` into
 * public/alcatraz/img and writes their pixel sizes to
 * src/alcatraz/data/images.ts, which the composition frames moves against.
 *
 * Usage:
 *   node tools/alcatraz-images.mjs <raw-dir>
 *
 * An optional `crop` [w, h, x, y] trims scanner borders first. Long side is capped at 2400 px: enough for a slow push on a 1080p frame,
 * small enough that the renderer is not decoding 50 MB scans every frame.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const raw = process.argv[2];
if (!raw) {
  console.error("Usage: node tools/alcatraz-images.mjs <raw-dir>");
  process.exit(1);
}

const { images } = JSON.parse(
  fs.readFileSync(new URL("./alcatraz-images.json", import.meta.url), "utf8"),
);
const outDir = path.resolve("public/alcatraz/img");
fs.mkdirSync(outDir, { recursive: true });

const sizes = {};
for (const [id, img] of Object.entries(images)) {
  const out = path.join(outDir, `${id}.jpg`);
  execFileSync(
    "ffmpeg",
    [
      "-v", "error", "-y",
      "-i", path.join(raw, img.src),
      "-vf",
      (img.crop ? `crop=${img.crop.join(":")},` : "") +
        "scale='if(gte(iw,ih),min(2400,iw),-2)':'if(gte(iw,ih),-2,min(2400,ih))':flags=lanczos,format=yuvj420p",
      "-q:v", "3",
      out,
    ],
    { stdio: "inherit" },
  );
  const [w, h] = execFileSync("ffprobe", [
    "-v", "error", "-select_streams", "v:0",
    "-show_entries", "stream=width,height", "-of", "csv=p=0", out,
  ])
    .toString()
    .trim()
    .split(",")
    .map(Number);
  sizes[id] = { w, h };
}

const lines = Object.entries(sizes).map(
  ([id, { w, h }]) => `  "${id}": { w: ${w}, h: ${h} },`,
);
fs.writeFileSync(
  path.resolve("src/alcatraz/data/images.ts"),
  `// Generated by tools/alcatraz-images.mjs. Do not edit by hand.\n` +
    `export const IMAGE_SIZES = {\n${lines.join("\n")}\n} as const;\n\n` +
    `export type ImageId = keyof typeof IMAGE_SIZES;\n`,
);
console.log(`${Object.keys(sizes).length} images`);
