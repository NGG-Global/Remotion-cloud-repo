/**
 * Cuts the archival footage for the Alcatraz documentary into the clips the
 * composition plays, as listed in `tools/alcatraz-media.json`.
 *
 * Usage:
 *   node tools/alcatraz-prep.mjs <raw-dir> [clip-id ...]
 *
 * <raw-dir> holds the downloaded source files at the paths the manifest names
 * (video/un1962_escape.mp4, ...). The sources are large and are not kept in the
 * repository; every one of them is listed with its archive URL in
 * public/alcatraz/SOURCES.md.
 *
 * Each clip is written once, already framed:
 *
 * - B-roll is cropped to 16:9 from inside the picture area (the newsreel
 *   transfers carry pillarbox and film edge), scaled to 1920x1080 and
 *   converted to 30 fps, without sound. Remotion then only has to play it.
 * - Inserts (`full`) keep the whole 4:3 frame at 1440x1080 with their own
 *   sound, because they are shown as archival documents rather than as
 *   picture under the narration.
 *
 * Short GOPs keep seeking cheap: the renderer asks for frames out of order.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const raw = process.argv[2];
const only = new Set(process.argv.slice(3));
if (!raw) {
  console.error("Usage: node tools/alcatraz-prep.mjs <raw-dir> [clip-id ...]");
  process.exit(1);
}

const manifest = JSON.parse(
  fs.readFileSync(new URL("./alcatraz-media.json", import.meta.url), "utf8"),
);
const outDir = path.resolve("public/alcatraz/clips");
fs.mkdirSync(outDir, { recursive: true });

const even = (n) => Math.round(n / 2) * 2;

for (const clip of manifest.clips) {
  if (only.size && !only.has(clip.id)) continue;
  const src = manifest.sources[clip.src];
  const [cw, ch, cx, cy] = manifest.crops[clip.src];
  const input = path.join(raw, src.file);
  const out = path.join(outDir, `${clip.id}.mp4`);

  let crop;
  let scale;
  if (clip.full) {
    crop = `crop=${cw}:${ch}:${cx}:${cy}`;
    scale = "scale=1440:1080:flags=lanczos";
  } else {
    // Largest 16:9 window inside the picture area, placed by fy.
    const w = Math.min(cw, even((ch * 16) / 9));
    const h = even((w * 9) / 16);
    const x = cx + even((cw - w) / 2);
    const y = cy + even((ch - h) * (clip.fy ?? 0.5));
    crop = `crop=${w}:${h}:${x}:${y}`;
    scale = "scale=1920:1080:flags=lanczos";
  }

  const filters = [crop, scale, "fps=30", "setsar=1", "format=yuv420p"];
  const args = [
    "-v", "error", "-y",
    "-ss", String(clip.in), "-to", String(clip.out),
    "-i", input,
    "-vf", filters.join(","),
    "-c:v", "libx264", "-preset", "medium", "-crf", "21",
    "-g", "15", "-keyint_min", "15", "-sc_threshold", "0",
    "-movflags", "+faststart",
  ];
  if (clip.full) {
    args.push("-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-ac", "2");
  } else {
    args.push("-an");
  }
  args.push(out);

  execFileSync("ffmpeg", args, { stdio: "inherit" });
  console.log(`${clip.id}: ${(clip.out - clip.in).toFixed(2)} s`);
}

// Record every clip's real length for the composition, which slows a clip
// down rather than letting a shot outrun it.
const lengths = manifest.clips.map((clip) => {
  const file = path.join(outDir, `${clip.id}.mp4`);
  const d = Number(
    execFileSync("ffprobe", [
      "-v", "error", "-select_streams", "v:0",
      "-show_entries", "stream=duration", "-of", "csv=p=0", file,
    ]).toString().trim(),
  );
  return `  "${clip.id}": ${d.toFixed(3)},`;
});
fs.writeFileSync(
  path.resolve("src/alcatraz/data/clips.ts"),
  `// Generated by tools/alcatraz-prep.mjs. Do not edit by hand.\n` +
    `export const CLIP_SECONDS = {\n${lengths.join("\n")}\n} as const;\n\n` +
    `export type ClipId = keyof typeof CLIP_SECONDS;\n`,
);
