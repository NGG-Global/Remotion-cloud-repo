/**
 * Writes docs/HIROSHIMA_SOURCES.md from the film registry and the stills'
 * provenance record, so the list cannot drift from what the edit uses.
 *
 *   node --experimental-strip-types tools/hiroshima/sources-doc.mjs
 */
import fs from "node:fs";

const { FILMS } = await import("../../src/hiroshima/data/sources.ts");
const st = JSON.parse(
  fs.readFileSync("public/hiroshima/stills/sources.json", "utf8"),
);
const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "/")
    .replace(/\s+/g, " ")
    .trim();

let md = "# Hiroshima and Nagasaki: sources and licences\n\n";
md +=
  "Every picture in `HiroshimaNagasaki` is listed here. Licence notes are as recorded on each source page when the material was downloaded (November 2026). Verify them before any use outside this project, and keep this list with any published copy of the film: the CC BY and CC BY-SA photographs below require attribution. The video credits them on screen when they appear and lists the archives in its end card; paste this list into the YouTube description.\n\n";
md += "Generated by `tools/hiroshima/sources-doc.mjs`.\n\n";
md +=
  "## Archival film\n\nDownloaded from the Internet Archive mirrors of U.S. National Archives holdings and of Universal Newsreel (`tools/hiroshima/fetch.mjs`), cut into `public/hiroshima/clips` by `tools/hiroshima/cut-clips.mjs`.\n\n";
md += "| Id | Film | Licence | Item page |\n| --- | --- | --- | --- |\n";
for (const [id, f] of Object.entries(FILMS)) {
  const page = f.url
    .replace("https://archive.org/download/", "https://archive.org/details/")
    .split("/")
    .slice(0, 5)
    .join("/");
  md += `| \`${id}\` | ${cell(f.title)} | ${cell(f.licence)} | ${page} |\n`;
}
md +=
  "\n## Photographs and documents\n\nFrom Wikimedia Commons. Files in `public/hiroshima/stills`; machine-readable record in `public/hiroshima/stills/sources.json`.\n\n";
md +=
  "| File | Commons page | Licence | Author / source | Date |\n| --- | --- | --- | --- | --- |\n";
for (const x of st) {
  md += `| \`${x.file}\` | [${cell(x.title.replace("File:", ""))}](${x.page}) | ${cell(x.license)} | ${cell(x.artist || x.credit).slice(0, 90)} | ${cell((x.date || "").replace(/date QS.*/, "")).slice(0, 40)} |\n`;
}
md += "\n## Other material\n\n";
md +=
  "- Map coastlines: Natural Earth 1:50m land polygons, public domain (naturalearthdata.com), projected into `src/hiroshima/data/land.ts`.\n";
md +=
  "- Fonts: Frank Ruhl Libre, Playfair Display and Rubik (SIL OFL 1.1, already in `public/fonts`); an eleven-glyph subset of Noto Serif JP for the Japanese words (SIL OFL 1.1, `public/fonts/NotoSerifJP-LICENSE.txt`).\n";
md +=
  "- Score and sound effects: synthesised by `tools/hiroshima/score.mjs`. No samples, no third-party music.\n";
md +=
  "- Narration: the three supplied files, `public/hiroshima/audio/narration-{1,2,3}.mp3`, byte-identical to the uploads.\n";
fs.writeFileSync("docs/HIROSHIMA_SOURCES.md", md);
console.log("wrote docs/HIROSHIMA_SOURCES.md");
