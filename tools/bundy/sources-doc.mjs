/**
 * Writes docs/BUNDY_SOURCES.md from the film registry and the stills'
 * provenance record, so the list cannot drift from what the edit uses.
 *
 *   node --experimental-strip-types tools/bundy/sources-doc.mjs
 */
import fs from "node:fs";

const { FILMS } = await import("../../src/bundy/data/sources.ts");
const st = JSON.parse(fs.readFileSync("public/bundy/stills/sources.json", "utf8"));
const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "/")
    .replace(/\s+/g, " ")
    .trim();

let md = "# Faces of Evil: Ted Bundy — sources and licences\n\n";
md +=
  "Every picture in `TedBundy` is listed here. Licence notes are as recorded on each source page when the material was downloaded (November 2026). Verify them before any use outside this project, and keep this list with any published copy of the film: the CC BY photograph below requires attribution. The video credits it on screen and lists the archives in its end card; paste this list into the YouTube description.\n\n";
md += "Generated by `tools/bundy/sources-doc.mjs`.\n\n";
md +=
  "## Moving pictures\n\nPeriod atmosphere only: all are U.S. government films, none shows Bundy, the victims or the places of the story, and the video credits each one on screen whenever it appears. A 1978 home movie from Prelinger Archives used in an early cut was removed because its item page states no licence and Prelinger's own FAQ says many of its films are not in the public domain. Downloaded from the Internet Archive into `.cache/raw-bundy`, cut and graded into `public/bundy/clips` by `tools/hiroshima/cut-clips.mjs bundy`.\n\n";
md += "| Id | Film | Licence | Item page |\n| --- | --- | --- | --- |\n";
for (const [id, f] of Object.entries(FILMS)) {
  const page = f.url
    .replace("https://archive.org/download/", "https://archive.org/details/")
    .split("/")
    .slice(0, 5)
    .join("/");
  md += `| \`${id}\` | ${cell(f.title)} | ${cell(f.licence)} | ${page} |\n`;
}
md +=
  "\n## Photographs and documents\n\nFiles in `public/bundy/stills`; machine-readable record in `public/bundy/stills/sources.json`. Photographs of Bundy come from the State Archives of Florida (Florida Memory), the Florida Department of Corrections and the FBI via Wikimedia Commons; the places are EPA DOCUMERICA photographs (U.S. National Archives) and Library of Congress photographs by Carol M. Highsmith and John Margolies. There are no photographs of the victims and none of crime scenes.\n\n";
md += "| Id | File | Source page | Licence | Author / source | Date |\n| --- | --- | --- | --- | --- | --- |\n";
for (const x of st) {
  md += `| \`${x.id}\` | \`${x.file}\` | [${cell(String(x.title).replace("File:", "")).slice(0, 70)}](${x.page}) | ${cell(x.license)} | ${cell(x.artist || x.credit).slice(0, 80)} | ${cell((x.date || "").replace(/date QS.*/, "")).slice(0, 40)} |\n`;
}
md += "\n## Other material\n\n";
md += "- Maps: Natural Earth 1:50m land and state boundaries, public domain (naturalearthdata.com), projected into `src/bundy/data/usmap.ts`.\n";
md += "- Fonts: Frank Ruhl Libre, Playfair Display and Rubik (SIL OFL 1.1, already in `public/fonts`).\n";
md += "- Score: synthesised by `tools/bundy/score.mjs`. No samples, no third-party music.\n";
md += "- Narration: the three supplied files, `public/bundy/audio/narration-{1,2,3}.mp3`, byte-identical to the uploads.\n";
fs.writeFileSync("docs/BUNDY_SOURCES.md", md);
console.log("wrote docs/BUNDY_SOURCES.md");
