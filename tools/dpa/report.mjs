/**
 * Writes the edit decision list as a readable document: docs/DPA_EDL.md.
 *
 *   node tools/dpa/report.mjs
 *
 * The JSON in src/dpa/data/edl.json stays the source of truth; this is the
 * same information laid out for a person to review against the narration.
 */
import fs from "node:fs";
import path from "node:path";
import { loadEdl, ROOT, timecode } from "./lib.mjs";

const edl = loadEdl();
const cell = (text) =>
  String(text ?? "")
    .replace(/\|/g, "/")
    .replace(/\n/g, " ");
const seconds = (shot) => (shot.to - shot.from) / edl.fps;

const chapters = [];
for (const shot of edl.shots) {
  let chapter = chapters[chapters.length - 1];
  if (!chapter || chapter.id !== shot.chapter) {
    chapter = { id: shot.chapter, shots: [] };
    chapters.push(chapter);
  }
  chapter.shots.push(shot);
}

const byGame = {};
for (const shot of edl.shots) {
  const entry = (byGame[shot.game] ??= { total: 0, sourced: 0, shots: 0 });
  entry.total += seconds(shot);
  entry.shots += 1;
  if (shot.source !== null) {
    entry.sourced += seconds(shot);
  }
}

const sourced = edl.shots.filter((shot) => shot.source !== null).length;
const lines = [
  "# The Dark Pictures Anthology: edit decision list",
  "",
  "Generated by `node tools/dpa/report.mjs` from `src/dpa/data/edl.json`. Do not edit by hand.",
  "",
  `Narration: \`public/${edl.narration}\`, ${timecode(edl.duration)} (${edl.duration.toFixed(2)} s, ${edl.total} frames at ${edl.fps} fps).`,
  `Shots: ${edl.shots.length}, of which ${sourced} have footage assigned and ${edl.shots.length - sourced} are waiting for it.`,
  "",
  "Times are narration time. A shot's out-point in its source is its in-point plus its length. Transitions describe how a shot arrives: `cut`, `dissolve` (12 frames, overlapping the outgoing shot) or `fade` (dip to black, 15 frames each side).",
  "",
  "## Footage required, by game",
  "",
  "| Game | Screen time | Shots | Covered so far |",
  "| --- | ---: | ---: | ---: |",
  ...Object.entries(byGame)
    .sort((a, b) => b[1].total - a[1].total)
    .map(
      ([game, e]) =>
        `| ${game} | ${timecode(e.total)} | ${e.shots} | ${timecode(e.sourced)} |`,
    ),
  "",
];

for (const chapter of chapters) {
  const first = chapter.shots[0];
  const last = chapter.shots[chapter.shots.length - 1];
  lines.push(
    `## ${chapter.id} (${timecode(first.from / edl.fps)} to ${timecode(last.to / edl.fps)})`,
    "",
    "| Shot | Start | End | Length | Game | Narration topic | Picture required | Source and in/out | Transition |",
    "| --- | ---: | ---: | ---: | --- | --- | --- | --- | --- |",
  );
  for (const shot of chapter.shots) {
    const length = seconds(shot);
    const source =
      shot.source === null
        ? "pending"
        : `\`${shot.source}\` ${timecode(shot.in)} to ${timecode(shot.in + length)}`;
    lines.push(
      `| ${shot.id} | ${timecode(shot.from / edl.fps)} | ${timecode(shot.to / edl.fps)} | ${length.toFixed(1)} s | ${cell(shot.game)} | ${cell(shot.topic)} | ${cell(shot.need)} | ${source} | ${shot.transition} |`,
    );
  }
  lines.push("");
}

const target = path.join(ROOT, "docs/DPA_EDL.md");
fs.writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${path.relative(ROOT, target)} (${edl.shots.length} shots)`);
